"""Производственный календарь РФ (нерабочие будни).

Помогает отличать рабочие дни (когда торги идут и ставка публикуется) от
нерабочих будних дней (государственные праздники, переносы выходных, особые
дни). Используется проверками покрытия рядов (ключевая ставка, дневные цены),
чтобы не считать праздничные дни за пропуски данных.
"""

from __future__ import annotations

from datetime import date, timedelta

# Фиксированные государственные праздники РФ (по месяц/день).
_FIXED_RU_HOLIDAYS: tuple[tuple[int, int], ...] = (
    *[(1, day) for day in range(1, 9)],  # новогодние каникулы 1–8 января
    (2, 23),  # День защитника Отечества
    (3, 8),  # Международный женский день
    (5, 1),  # Праздник Весны и Труда
    (5, 9),  # День Победы
    (6, 12),  # День России
    (11, 4),  # День народного единства
)

# Переносы выходных (праздник попадал на сб/вс) и особые нерабочие дни.
# Изменяются по годам, поэтому зафиксированы явно для периода наблюдения
# исследования (2014–2026).
_MOVED_AND_SPECIAL: tuple[str, ...] = (
    "2014-03-10",
    "2014-05-02",
    "2014-06-13",
    "2014-11-03",
    "2015-01-09",
    "2015-03-09",
    "2015-05-04",
    "2015-05-11",
    "2016-02-22",
    "2016-03-07",
    "2016-05-02",
    "2016-05-03",
    "2016-06-13",
    "2017-02-24",
    "2017-05-08",
    "2017-11-06",
    "2018-03-09",
    "2018-04-30",
    "2018-05-02",
    "2018-06-11",
    "2018-11-05",
    "2018-12-31",
    "2019-05-02",
    "2019-05-03",
    "2019-05-10",
    "2020-02-24",
    "2020-03-09",
    "2020-05-11",
    "2020-06-24",
    "2020-07-01",
    "2021-05-03",
    "2021-05-10",
    "2021-12-31",
    "2022-03-07",
    "2022-05-02",
    "2022-05-03",
    "2022-05-10",
    "2022-06-13",
    "2024-12-31",
    "2025-12-31",
)


def build_ru_non_workdays(from_date: date, to_date: date) -> set[date]:
    """Нерабочие будни в интервале: праздники РФ + переносы/особые дни.

    Возвращает множество дат, в которые торги и публикация ставки не идут,
    несмотря на то что это будни. Используется, чтобы не считать такие дни
    пропусками данных.
    """
    result: set[date] = set()
    # Фиксированные праздники.
    current = from_date
    while current <= to_date:
        if (current.month, current.day) in _FIXED_RU_HOLIDAYS:
            result.add(current)
        current = current + timedelta(days=1)
    # Переносы и особые дни.
    for item in _MOVED_AND_SPECIAL:
        day = date.fromisoformat(item)
        if from_date <= day <= to_date:
            result.add(day)
    return result